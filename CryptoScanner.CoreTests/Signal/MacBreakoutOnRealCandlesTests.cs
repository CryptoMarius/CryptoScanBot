    /// <summary>One line per candle: date, high, low, close.</summary>
    private static List<CryptoCandle> Parse(string block)
    {
        CryptoInterval interval = GlobalData.IntervalListPeriod[CryptoIntervalPeriod.interval1d];
        var candles = new List<CryptoCandle>();
        foreach (string line in block.Split('\n'))
        {
            string[] field = line.Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries);
            if (field.Length != 4)
                continue;

            decimal close = Number(field[3]);
            candles.Add(new CryptoCandle
            {
                TickDecimals = 2,
                OpenTime = CandleTime.AlignFromDateTime(
                    DateTime.SpecifyKind(DateTime.Parse(field[0], Invariant), DateTimeKind.Utc),
                    interval.Duration),
                Open = close,
                High = Number(field[1]),
                Low = Number(field[2]),
                Close = close,
                Volume = 100m,
            });
        }
        return candles;
    }

