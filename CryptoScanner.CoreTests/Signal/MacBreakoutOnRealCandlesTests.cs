    /// <summary>
    /// The marker sits UNDER the candle, the side a breakout is drawn on, and it takes its
    /// colour from the key the chart style screen knows it by.
    /// </summary>
    [TestMethod]
    public void TheMarkerSitsUnderTheCandle()
    {
        var candles = Parse(Autumn2024);
        Exchange exchange = new() { Id = 1, Name = "TestExchange", FeeRate = 0.1m };
        CryptoSymbol symbol = new()
        {
            Id = 1,
            Name = "BTCUSDT",
            Base = "BTC",
            Quote = "USDT",
            Exchange = exchange,
            ExchangeId = exchange.Id,
            ExchangeName = exchange.Name,
            QuoteData = GlobalData.AddQuoteData("USDT"),
            PriceTickSize = 0.01m,
        };
        CryptoInterval interval = GlobalData.IntervalListPeriod[CryptoIntervalPeriod.interval1d];

        var marks = new MacChartOverlay().GetLabels(symbol, interval, candles)
            .Where(l => l.StyleKey == MacChartOverlay.KeyBreakout).ToList();

        Assert.IsTrue(marks.Count > 0, "the stretch should carry breakouts");
        foreach (var mark in marks)
        {
            Assert.IsFalse(mark.Above, "a breakout is drawn under the candle");
            var candle = candles.Find(c => CandleTime.AlignFromDateTime(c.Date, interval.Duration)
                .ToUnixSeconds() == mark.Time);
            Assert.AreEqual((double)candle.Low, mark.Price, "anchored to the low of its candle");
        }
    }
